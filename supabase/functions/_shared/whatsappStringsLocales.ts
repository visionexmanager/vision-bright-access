/**
 * The same table, by key.
 *
 * Transposed once at module load into the shape `whatsappStrings.ts` folds in.
 * Authoring by language and reading by key is the whole reason for the
 * transposition: a translator works down a column, and the code looks up a row.
 */
export const UI_TEXT: Readonly<Record<string, Partial<Record<SupportedLanguage, string>>>> = (() => {
  const out: Record<string, Partial<Record<SupportedLanguage, string>>> = {};
  for (const [language, vocabulary] of Object.entries(BY_LANGUAGE)) {
    for (const [key, value] of Object.entries(vocabulary ?? {})) {
      (out[key] ??= {})[language as SupportedLanguage] = value;
    }
  }
  return out;
})();
