// The interface's vocabulary, in the other eighteen languages.
//
// `whatsappStrings.ts` declares every sentence in English and Arabic inline —
// which is what somebody adding a string has to write — and this fills in the
// rest. Folded together once at module load, so nothing downstream looks a
// sentence up in two places.
//
// ── The three that have hard limits ─────────────────────────────────────────
//
//   menuButton  20 characters. Meta rejects a longer list button outright.
//   back        24 characters. It is a row title.
//   mainMenu    24 characters, the same.
//   the gender and country rows, likewise 24.
//
// Rejected, not truncated: a message one character over is not delivered at
// all, and the sender is left staring at nothing. A test measures every one of
// them in every language rather than trusting the eye.
//
// `comingSoon` carries a `{name}` placeholder in every language. A translation
// that drops it produces a sentence that names no feature, so the suite fails
// on a missing placeholder rather than shipping one.
//
// Pure data. No `Deno`, no fetch, no database.

