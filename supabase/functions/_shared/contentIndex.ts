// The semantic index the assistants and the content engine read from.
//
// Moved out of embed-content so the daily content run can fill a section that
// has never been indexed, with exactly the same rules the admin button uses:
// only published, active rows, and never anything that identifies a child.

import { createEmbedding } from "./aiProvider.ts";
import servicesCatalog from "./data/servicesCatalog.json" with { type: "json" };

// deno-lint-ignore no-explicit-any
type ServiceClient = any;

/**
 * Services are a code catalogue, not a table — the approved Phase 1 decision
 * was to index it rather than duplicate it into the database. This snapshot is
 * generated by `npx vite-node scripts/generate-services-index.ts` and kept in
 * step by src/test/services-index.test.ts.
 *
 * It is indexed into the same `ai_embeddings` table under the virtual source
 * name `services`, so retrieval stays one system.
 */
export const SERVICES_SOURCE = "services";

interface IndexedService {
  id: string;
  text: string;
}

// Which tables get embedded and how their searchable text is built.
//
// Phase 1 widened this from two tables to the user-facing domains the AI Core
// is expected to know about. Three deliberate exclusions:
//
//  - `library_books` already carries its own `embedding` column and is served
//    by library-semantic-search / library-embed-book. Indexing it here too
//    would be a second semantic system for the same rows, which the spec
//    forbids. Cross-domain queries reach the library through that index.
//  - Anything under `kids_*` that identifies a child. Only the public
//    catalogue of games is indexed, never progress, messages or profiles.
//  - Tables with no user-facing text worth retrieving.
//
// `filter` keeps unpublished and inactive rows out of the index, so the AI
// cannot recommend something a visitor cannot reach.
interface SourceConfig {
  columns: string;
  toText: (r: Record<string, unknown>) => string;
  /** Applied as .eq() pairs; keeps drafts and disabled rows unindexed. */
  filter?: Record<string, unknown>;
}

