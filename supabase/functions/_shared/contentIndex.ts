const BATCH = 50;

/**
 * The id a catalogue service is stored under.
 *
 * `ai_embeddings.source_id` is a uuid and catalogue ids are slugs
 * ("egg-incubator"), so every services upsert used to fail and the catalogue
 * was never searchable. A slug is turned into a stable name-based uuid
 * (SHA-256, version 5 layout) instead; the slug itself travels in `content`.
 */
export async function serviceSourceId(slug: string): Promise<string> {
  const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(`visionex:services:${slug}`)));
  const bytes = digest.slice(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

/** Catalogue services by their stored id, for turning a match back into a service. */
let servicesByStoredId: Promise<Map<string, IndexedService>> | null = null;
export function catalogServicesByStoredId(): Promise<Map<string, IndexedService>> {
  servicesByStoredId ??= Promise.all(
    (servicesCatalog as IndexedService[]).map(async (s) => [await serviceSourceId(s.id), s] as const),
  ).then((pairs) => new Map(pairs));
  return servicesByStoredId;
}

/** Every source name the index knows. */
export const INDEX_SOURCES: string[] = [...Object.keys(SOURCES), SERVICES_SOURCE];

/**
 * (Re)build the index for the given sources. Returns how many rows each got;
 * -1 for a table that could not be read.
 */
export async function indexSources(
  service: ServiceClient,
  requested: string[],
  options: { limit?: number } = {},
): Promise<Record<string, number>> {
  const tables = requested.filter((t) => t !== SERVICES_SOURCE && SOURCES[t]);
  const indexServices = requested.includes(SERVICES_SOURCE);
  const limit = Math.min(Math.max(options.limit ?? 2000, 1), 2000);

  const summary: Record<string, number> = {};

  for (const table of tables) {
    const cfg = SOURCES[table];
    let query = service.from(table).select(cfg.columns).limit(limit);
    for (const [column, value] of Object.entries(cfg.filter ?? {})) {
      query = query.eq(column, value);
    }
    const { data: rows, error } = await query;
    // One table failing — a column renamed, a table not yet deployed — must
    // not abandon the tables that would have indexed fine.
    if (error) {
      console.error(`[embed-content] skipping ${table}:`, error.message);
      summary[table] = -1;
      continue;
    }
    if (!rows || rows.length === 0) { summary[table] = 0; continue; }

    let embedded = 0;
    for (let i = 0; i < rows.length; i += BATCH) {
      const chunk = rows.slice(i, i + BATCH) as Array<Record<string, unknown>>;
      const texts = chunk.map((r) => cfg.toText(r).slice(0, 6000));
      const vectors = await createEmbedding(texts);

      const upserts = chunk.map((r, j) => ({
        source_table: table,
        source_id: r.id,
        content: texts[j],
        embedding: vectors[j],
        updated_at: new Date().toISOString(),
      }));
      const { error: upErr } = await service
        .from("ai_embeddings")
        .upsert(upserts, { onConflict: "source_table,source_id" });
      if (upErr) throw upErr;
      embedded += upserts.length;
    }
    summary[table] = embedded;
  }

  // Services come from the committed catalogue snapshot rather than a table,
  // but land in the same ai_embeddings store under the `services` source, so
  // one semantic search covers them alongside everything else.
  if (indexServices) {
    const services = servicesCatalog as IndexedService[];
    let embedded = 0;
    for (let i = 0; i < services.length; i += BATCH) {
      const chunk = services.slice(i, i + BATCH);
      const vectors = await createEmbedding(chunk.map((s) => s.text.slice(0, 6000)));
      const ids = await Promise.all(chunk.map((s) => serviceSourceId(s.id)));
      const { error: upErr } = await service.from("ai_embeddings").upsert(
        chunk.map((s, j) => ({
          source_table: SERVICES_SOURCE,
          source_id: ids[j],
          content: s.text,
          embedding: vectors[j],
          updated_at: new Date().toISOString(),
        })),
        { onConflict: "source_table,source_id" },
      );
      if (upErr) throw upErr;
      embedded += chunk.length;
    }
    summary[SERVICES_SOURCE] = embedded;
  }

  return summary;
}
