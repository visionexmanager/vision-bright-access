// The menu, in the other eighteen languages.
//
// `whatsappCatalog.ts` declares each node with English and Arabic inline —
// which is all somebody adding a feature has to write — and this supplies the
// rest. Keyed by node id, folded into the tree once at module load, so nothing
// downstream ever looks a label up in two places.
//
// ── Why the split ───────────────────────────────────────────────────────────
//
// Not because translations are second class. Because the catalog is the file a
// developer edits to add a feature, and a file where every new entry demands
// twenty translations before it compiles is a file where features stop getting
// added. A missing language here costs an English label and nothing else, and
// the suite reports exactly which nodes are short.
//
// ── The two limits that matter ──────────────────────────────────────────────
//
// Meta truncates nothing: a row title over 24 characters, or a description over
// 72, rejects the whole message and the sender receives silence. Every string
// below is inside both, and a test walks all of them in every language rather
// than trusting that.
//
// Titles are noun phrases, not sentences, and never an abbreviation: this menu
// is read aloud by a screen reader far more often than it is looked at, and
// "OCR" spoken is three letters, not a feature.
//
// Pure data. No `Deno`, no fetch, no database.

