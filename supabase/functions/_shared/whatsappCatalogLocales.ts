/** One node's labels, in every language written for it. */
export interface NodeText {
  title: Partial<Record<SupportedLanguage, string>>;
  description: Partial<Record<SupportedLanguage, string>>;
}

/**
 * The same table, by node id.
 *
 * Transposed once at module load rather than kept in both shapes: two hand-
 * maintained copies of the same strings is exactly the drift this whole file
 * exists to avoid.
 */
export const NODE_TEXT: Readonly<Record<string, NodeText>> = (() => {
  const out: Record<string, NodeText> = {};
  for (const [language, entries] of Object.entries(BY_LANGUAGE)) {
    for (const [id, [title, description]] of Object.entries(entries ?? {})) {
      const node = out[id] ??= { title: {}, description: {} };
      node.title[language as SupportedLanguage] = title;
      node.description[language as SupportedLanguage] = description;
    }
  }
  return out;
})();
